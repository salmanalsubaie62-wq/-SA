"use client";

import { useEffect, useState } from "react";
import { Icon } from "./Icon";
import { ConnectionBadge, EmptyState, ErrorText, Notice, PageHead, Spinner, toast } from "./ui";
import { api } from "@/lib/client/api";

const ASPECTS = [
  { id: "1:1", label: "1:1 Square" },
  { id: "16:9", label: "16:9 Landscape" },
  { id: "9:16", label: "9:16 Portrait" },
  { id: "4:3", label: "4:3" },
  { id: "3:4", label: "3:4" },
] as const;
const STYLES = ["Photorealistic", "Anime", "Cartoon", "Pixel art", "Cinematic", "3D character", "Game environment", "Product photography", "Concept art", "Logo", "Poster", "Illustration", "Watercolor", "Minimal flat"];

const TOOLS = [
  { name: "Generate images", ready: true, note: "Text-to-image via OpenAI Images (gpt-image-1)." },
  { name: "Variations", ready: true, note: "Run the same brief again for alternatives." },
  { name: "Edit / modify objects", ready: false, note: "Needs an image-editing provider with masks." },
  { name: "Remove or replace background", ready: false, note: "Needs a segmentation provider." },
  { name: "Expand (outpaint) & upscale", ready: false, note: "Needs an upscaling provider." },
  { name: "Reference images & character consistency", ready: false, note: "Needs an image-to-image provider." },
];

interface GalleryItem {
  id: string;
  title: string;
  prompt: string;
  params: { aspect: string; style?: string | null };
  url: string | null;
  createdAt: number;
}

export function ImageStudio() {
  const [connected, setConnected] = useState<boolean | null>(null);
  const [prompt, setPrompt] = useState("");
  const [aspect, setAspect] = useState<(typeof ASPECTS)[number]["id"]>("1:1");
  const [style, setStyle] = useState("");
  const [lighting, setLighting] = useState("");
  const [camera, setCamera] = useState("");
  const [count, setCount] = useState(1);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [items, setItems] = useState<GalleryItem[]>([]);
  const [lightbox, setLightbox] = useState<GalleryItem | null>(null);

  const load = async () => {
    const data = await api<{ connected: boolean; items: GalleryItem[] }>("/api/images");
    setConnected(data.connected);
    setItems(data.items);
  };

  useEffect(() => {
    load().catch((err) => setError(err.message));
  }, []);

  const generate = async (override?: Partial<{ prompt: string }>) => {
    const text = (override?.prompt ?? prompt).trim();
    if (text.length < 3) return setError("Describe the image in at least 3 characters.");
    setBusy(true);
    setError(null);
    try {
      await api("/api/images", { body: { prompt: text, aspect, style: style || undefined, lighting: lighting || undefined, camera: camera || undefined, count } });
      toast(`${count > 1 ? `${count} images` : "Image"} created`, "success");
      await load();
    } catch (err) {
      setError(err instanceof Error ? err.message : "Generation failed.");
    } finally {
      setBusy(false);
    }
  };

  const remove = async (item: GalleryItem) => {
    if (!window.confirm("Delete this image?")) return;
    await api(`/api/media/${item.id}`, { method: "DELETE" });
    setLightbox(null);
    await load();
  };

  return (
    <div>
      <PageHead
        title="Image Studio"
        subtitle="Describe any image: photorealistic, anime, pixel art, product shots, logos, posters and more. Files are generated by a real image API and stored in your gallery."
        actions={connected !== null && <ConnectionBadge connected={connected} label={connected ? "Image API connected" : "Image API not connected"} />}
      />
      {connected === false && (
        <div style={{ marginBottom: 18 }}>
          <Notice kind="warning" title="Image generation is not connected">
            Add <code>OPENAI_API_KEY</code> to the server environment and restart OMNIA. Until then no images are generated and none are simulated.
          </Notice>
        </div>
      )}
      <div className="studio">
        <div className="stack">
          <div className="card stack">
            <label className="field">
              Prompt
              <textarea
                value={prompt}
                onChange={(e) => setPrompt(e.target.value)}
                placeholder="A cinematic night street in Riyadh, rain reflections, a lone cyclist, warm neon signs, 35mm film look…"
                rows={5}
                maxLength={4000}
              />
            </label>
            <div className="field">
              <span>Aspect ratio</span>
              <div className="chips">
                {ASPECTS.map((a) => (
                  <button key={a.id} className="chip" aria-pressed={aspect === a.id} onClick={() => setAspect(a.id)}>
                    {a.label}
                  </button>
                ))}
              </div>
            </div>
            <div className="grid grid-2" style={{ gap: 12 }}>
              <label className="field">
                Visual style
                <select value={style} onChange={(e) => setStyle(e.target.value)}>
                  <option value="">Auto</option>
                  {STYLES.map((s) => (
                    <option key={s}>{s}</option>
                  ))}
                </select>
              </label>
              <label className="field">
                Number of images
                <select value={count} onChange={(e) => setCount(Number(e.target.value))}>
                  {[1, 2, 3, 4].map((n) => (
                    <option key={n} value={n}>{n}</option>
                  ))}
                </select>
              </label>
              <label className="field">
                Lighting
                <input value={lighting} onChange={(e) => setLighting(e.target.value)} placeholder="golden hour, soft studio…" maxLength={120} />
              </label>
              <label className="field">
                Camera angle
                <input value={camera} onChange={(e) => setCamera(e.target.value)} placeholder="low angle, 85mm portrait…" maxLength={120} />
              </label>
            </div>
            <ErrorText message={error} />
            <button className="btn btn-primary" onClick={() => generate()} disabled={busy || connected === false} style={{ minHeight: 44 }}>
              {busy ? <Spinner label="Generating…" /> : (<><Icon name="sparkle" size={16} /> Generate</>)}
            </button>
          </div>

          <div className="card stack" style={{ padding: 16 }}>
            <h3 style={{ margin: 0 }}>Studio tools</h3>
            {TOOLS.map((tool) => (
              <div key={tool.name} className="row-between" style={{ alignItems: "flex-start" }}>
                <div>
                  <div style={{ fontSize: "0.9rem" }}>{tool.name}</div>
                  <div className="small muted">{tool.note}</div>
                </div>
                <span className={`badge ${tool.ready ? (connected ? "badge-ok" : "badge-off") : "badge-off"}`}>
                  {tool.ready ? (connected ? "Ready" : "Needs key") : "Not connected"}
                </span>
              </div>
            ))}
          </div>
        </div>

        <div>
          <div className="row-between" style={{ marginBottom: 12 }}>
            <h2 style={{ margin: 0 }}>Gallery</h2>
            <span className="small muted">{items.length} item{items.length === 1 ? "" : "s"}</span>
          </div>
          {busy && (
            <div className="gallery" style={{ marginBottom: 14 }}>
              {Array.from({ length: count }).map((_, i) => (
                <div key={i} className="skeleton" style={{ aspectRatio: "1" }} />
              ))}
            </div>
          )}
          {items.length === 0 && !busy ? (
            <EmptyState icon="image" title="Your gallery is empty">
              Write a prompt and generate your first image. Every creation stays here, downloadable and organized.
            </EmptyState>
          ) : (
            <div className="gallery">
              {items.map((item) => (
                <div key={item.id} className="gallery-item">
                  {item.url && (
                    <button
                      onClick={() => setLightbox(item)}
                      aria-label={`Open: ${item.title}`}
                      style={{ all: "unset", cursor: "zoom-in", display: "block", width: "100%", height: "100%" }}
                    >
                      <img src={item.url} alt={item.prompt} loading="lazy" />
                    </button>
                  )}
                  <div className="gallery-cap">
                    <span style={{ overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>{item.title}</span>
                    <span className="mono" style={{ opacity: 0.8 }}>{item.params.aspect}</span>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      </div>

      {lightbox && lightbox.url && (
        <div
          role="dialog"
          aria-modal="true"
          onClick={() => setLightbox(null)}
          style={{ position: "fixed", inset: 0, background: "rgba(5,5,5,0.86)", zIndex: 80, display: "grid", placeItems: "center", padding: 20, animation: "fade .2s" }}
        >
          <div onClick={(e) => e.stopPropagation()} className="card" style={{ maxWidth: 980, width: "100%", padding: 14 }}>
            <img src={lightbox.url} alt={lightbox.prompt} style={{ width: "100%", maxHeight: "70vh", objectFit: "contain", borderRadius: 14 }} />
            <div className="row-between" style={{ marginTop: 12 }}>
              <div className="small dim" style={{ maxWidth: "60ch" }}>{lightbox.prompt}</div>
              <div className="row">
                <a className="btn btn-sm" href={lightbox.url} download={`omnia-${lightbox.id}.png`}>
                  <Icon name="download" size={14} /> Download
                </a>
                <button className="btn btn-sm" onClick={() => { setPrompt(lightbox.prompt); setLightbox(null); window.scrollTo({ top: 0, behavior: "smooth" }); }}>
                  <Icon name="refresh" size={14} /> Variation brief
                </button>
                <button className="btn btn-sm btn-danger" onClick={() => remove(lightbox)}>
                  <Icon name="trash" size={14} /> Delete
                </button>
                <button className="btn btn-sm" onClick={() => setLightbox(null)}>Close</button>
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
